"""Создание базы данных и демо-клиента «Импульс». Запускается один раз:
    python seed.py
Повторный запуск не задвоит данные."""

from app import db


def main() -> None:
    db.init_db()
    if db.list_tenants():
        print("База уже создана, тенанты на месте — ничего не делаю.")
        return

    tenant_id = db.create_tenant(
        name="Фитнес-клуб «Импульс»",
        industry="фитнес-клуб в спальном районе, аудитория 25-45 лет",
        brand_profile={
            "tone": "дружелюбно, энергично, на «вы», без канцелярита и пафоса, "
                    "можно лёгкий юмор, 1-3 эмодзи на пост",
            "stop_words": ["гарантия результата", "лучший в городе",
                           "самый дешёвый", "№1", "уникальный"],
            "cta_words": ["запишитесь", "приходите", "пишите", "звоните",
                          "жмите", "переходите", "забронируйте", "успейте"],
        },
    )
    plan = [
        ("Открытие утренних групп по йоге с 1 августа", "telegram",
         "фото: зал с панорамными окнами на рассвете, инструктор раскладывает коврики"),
        ("История клиентки: минус 12 кг за полгода без жёстких диет", "instagram",
         "коллаж до/после, женщина 35 лет улыбается в тренажёрном зале"),
        ("Скидка 20% на годовой абонемент до конца июля", "max",
         "видео 15 сек: динамичная нарезка тренировок, в конце — таймер"),
    ]
    for theme, channel, media in plan:
        db.add_plan_item(tenant_id, theme, channel, media)

    print(f"Готово: создан тенант #{tenant_id} и контент-план из {len(plan)} позиций.")
    print("Запускайте панель:  python run_web.py")


if __name__ == "__main__":
    main()
